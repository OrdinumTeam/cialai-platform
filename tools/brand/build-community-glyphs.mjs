// traçado abaixo e o oficial, o mesmo que o site usa no seu sprite. O PNG sai
// preto sobre transparente e a interface aplica `tintColor`, entao um arquivo
// so serve ao tema claro e ao escuro.
//
// Uso: node tools/brand/build-community-glyphs.mjs
