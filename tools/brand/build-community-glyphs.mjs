const { chromium } = createRequire(`${root}tools/browser/run-browser-checks.mjs`)('playwright');
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: TAMANHO, height: TAMANHO } });
for (const marca of MARCAS) {
  await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent">
    <svg xmlns="http://www.w3.org/2000/svg" width="${TAMANHO}" height="${TAMANHO}" viewBox="0 0 24 24" fill="#000"><path d="${marca.path}"/></svg>
  </body></html>`);
  const png = await page.locator('svg').screenshot({ omitBackground: true });
  writeFileSync(`${SAIDA}/${marca.nome}.png`, png);
  console.log(`${marca.nome}.png ${TAMANHO}x${TAMANHO}, ${png.length} bytes`);
}
await browser.close();
